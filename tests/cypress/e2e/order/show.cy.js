describe('Order-Show', () => {
    beforeEach(() => {
        cy.visit("/login/logout");
        cy.dbSeed();
        cy.visit("/");
    });

    it('can finish an order by doing customer steps, admin steps and check it as a customer', () => {
        cy.loginAs('customer');
        cy.visit("/");
        cy.query('nav-catalog').click();
        cy.query('catalog_list_card').contains('Classic 2-Eye Bootsschuh').click();
        cy.query('variant_size').contains('40').click();
        cy.query('variant_color').contains('blau').click();
        cy.query('variant_add_to_cart').click();
        cy.query('order_gross').contains('155.00 €');
        cy.query('order_net').contains('130.25 €');
        cy.query('order_tax').contains('24.75 €');
        cy.query('order-raise').click();
        cy.query('order_gross').contains('310.00 €');
        cy.query('order-raise').click();
        cy.query('order_gross').contains('465.00 €');
        cy.query('order-reduce').click();
        cy.query('order_gross').contains('310.00 €');
        cy.query('order-checkout').click();
        cy.query('order_gross').contains('310.00 €');
        cy.form('recipient').type('Udo Latteck');
        cy.form('address_line_1').type('Udo Latteck Strasse 1');
        cy.form('postal_code').type('23456');
        cy.form('city').type('Downtown');
        cy.query('order-address-form').contains('Bestellung').click();
        cy.query('order_gross').contains('310.00 €');
        cy.query('order-status').contains('pending');
        cy.loginAs('admin');
        cy.visit("/");
        cy.query('nav-all-order').click();
        cy.query('order-element-link').first().click();
        cy.query('order-status-option').should('have.length', 2);
        cy.form('status').contains('confirmed');
        cy.form('status').contains('cancelled');
        cy.form('status').select('confirmed');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('confirmed');
        cy.query('order-status-option').should('have.length', 2);
        cy.form('status').contains('paid');
        cy.form('status').contains('cancelled');
        cy.form('status').select('paid');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('paid');
        cy.query('order-status-option').should('have.length', 2);
        cy.form('status').contains('shipped');
        cy.form('status').contains('cancelled');
        cy.form('status').select('shipped');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('shipped');
        cy.query('order-status-option').should('have.length', 1);
        cy.form('status').contains('completed');
        cy.form('status').select('completed');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('completed');
        cy.form('status').should('not.exist');
        cy.loginAs('customer');
        cy.visit("/");
        cy.query('nav-own-order').click();
        cy.query('order-element-link').first().click();
        cy.query('order-status').contains('completed');
        cy.query('order-element-link').contains('Classic 2-Eye Bootsschuh');
        cy.query('order_gross').contains('310.00 €');
        cy.query('order_net').contains('260.50 €');
        cy.query('order_tax').contains('49.50 €');
        cy.query('order-address').contains('Udo Latteck');
    });

    it('can take over a guest cart after login, finish the order as admin and check it as a customer', () => {
        cy.query('usernameNav');
        cy.query('nav-catalog').click();
        cy.query('catalog_list_card').contains('Classic 2-Eye Bootsschuh').click();
        cy.query('variant_size').contains('40').click();
        cy.query('variant_color').contains('blau').click();
        cy.query('variant_add_to_cart').click();
        cy.query('order_gross').contains('155.00 €');
        cy.query('order_net').contains('130.25 €');
        cy.query('order_tax').contains('24.75 €');
        cy.query('order-raise').click();
        cy.query('order_gross').contains('310.00 €');
        cy.query('order-raise').click();
        cy.query('order_gross').contains('465.00 €');
        cy.query('order-reduce').click();
        cy.query('order_gross').contains('310.00 €');
        cy.query('usernameNav').type('customer@zubzet.com');
        cy.query('passwordNav').type('password');
        cy.query('btn-loginNav').click();
        cy.query('nav-user').contains('customer@zubzet.com');
        cy.query('nav-cart').click();
        cy.query('order-element-link').contains('Classic 2-Eye Bootsschuh');
        cy.query('order_gross').contains('310.00 €');
        cy.query('order_net').contains('260.50 €');
        cy.query('order_tax').contains('49.50 €');
        cy.visit("/");
        cy.query('nav-cart').click();
        cy.query('order-element-link').contains('Classic 2-Eye Bootsschuh');
        cy.query('order_gross').contains('310.00 €');
        cy.query('order-checkout').click();
        cy.query('order_gross').contains('310.00 €');
        cy.form('recipient').type('Udo Latteck');
        cy.form('address_line_1').type('Udo Latteck Strasse 1');
        cy.form('postal_code').type('23456');
        cy.form('city').type('Downtown');
        cy.query('order-address-form').contains('Bestellung').click();
        cy.query('order_gross').contains('310.00 €');
        cy.query('order-status').contains('pending');
        cy.loginAs('admin');
        cy.visit("/");
        cy.query('nav-all-order').click();
        cy.query('order-element-link').first().click();
        cy.form('status').select('confirmed');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('confirmed');
        cy.form('status').select('paid');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('paid');
        cy.form('status').select('shipped');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('shipped');
        cy.form('status').select('completed');
        cy.query('order_status_form').contains('speichern').click();
        cy.query('order-status').contains('completed');
        cy.loginAs('customer');
        cy.visit("/");
        cy.query('nav-own-order').click();
        cy.query('order-element-link').first().click();
        cy.query('order-status').contains('completed');
        cy.query('order-element-link').contains('Classic 2-Eye Bootsschuh');
        cy.query('order_gross').contains('310.00 €');
        cy.query('order_net').contains('260.50 €');
        cy.query('order_tax').contains('49.50 €');
        cy.query('order-address').contains('Udo Latteck');
        cy.query('order-address').contains('Udo Latteck Strasse 1');
        cy.query('order-address').contains('23456 Downtown');
        cy.query('order-address').contains('Deutschland');
    });

    it('placing an order and try to raise the amount higher than stock available', () => {
        cy.loginAs('customer');
        cy.visit("/");
        cy.query('nav-catalog').click();
        cy.query('catalog_list_card').contains('Air Force 1 \'07').click();
        cy.query('variant_size').contains('51.5').click();
        cy.query('variant_color').contains('Schwarz').click();
        cy.query('variant_add_to_cart').click();
        cy.query('order_gross').contains('124.99 €');
        cy.query('order-raise').click();
        cy.get('#cartNotification').contains('Lagerbestand reicht nicht aus.').click();
        cy.query('order_gross').contains('124.99 €');
        cy.query('nav-catalog').click();
        cy.query('catalog_list_card').contains('Air Max 90').click();
        cy.query('variant_size').contains('40').click();
        cy.query('variant_color').contains('Smoke').click();
        cy.query('variant_add_to_cart').click();
        cy.query('order_gross').contains('274.98 €');
        cy.query('order-raise').last().click();
        cy.query('order_gross').contains('424.97 €');
        cy.query('order-raise').last().click();
        cy.query('order_gross').contains('574.96 €');
        cy.query('order-reduce').last().click();
        cy.query('order_gross').contains('424.97 €');
        cy.query('order-reduce').first().click();
        cy.query('order-element-link').contains('Air Force 1 \'07').should('not.exist');
        cy.query('order-element-link').contains('Air Max 90');
        cy.query('order_gross').contains('299.98 €');
        cy.query('order_net').contains('252.08 €');
        cy.query('order_tax').contains('47.90 €');
        cy.query('order-checkout').click();
        cy.query('order_gross').contains('299.98 €');
        cy.form('recipient').type('Udo Latteck');
        cy.form('address_line_1').type('Udo Latteck Strasse 1');
        cy.form('postal_code').type('23456');
        cy.form('city').type('Downtown');
        cy.query('order-address-form').contains('Bestellung').click();
        cy.query('order-status').contains('pending');
        cy.query('order_gross').contains('299.98 €');
        cy.query('nav-own-order').click();
        cy.query('order-element-link').first().click();
        cy.query('order-status').contains('pending');
        cy.query('order-element-link').contains('Air Max 90');
        cy.query('order_gross').contains('299.98 €');
        cy.query('order_net').contains('252.08 €');
        cy.query('order_tax').contains('47.90 €');
        cy.query('order-address').contains('Udo Latteck');
        cy.query('nav-cart').click();
        cy.get('body').contains('Dein Warenkorb ist leer.');
    });
});
